#!/usr/bin/env python3
"""
team_config.py - build the Conan configuration the team installs with `conan config install`.

Standard library only (Python 3.11+). Used by the Conan Mirror GUI (Export team config, and
the Verify step, which installs from Nexus in a clean Conan home made from this same config).

The configuration is a plain folder in the layout of a Conan home:

    remotes.json                                        only the Nexus remote
    global.conf                                         sources for --build=missing come from Nexus
    profiles/<name>                                     the team profiles
    extensions/plugins/compatibility/compatibility.py   MSVC fallbacks (e.g. 195 may use 194)
    README.txt, .conanignore                            instructions (not copied into Conan)

Developers install it with one command, from the zip or from a URL:

    conan config install team-config.zip
    conan config install https://nexus.corp/repository/conan-sources/config/team-config.zip

`conan config install` REPLACES remotes.json, global.conf and the compatibility plugin in the
developer's Conan home, and adds/overwrites the profiles. Running it again updates them.
"""
from __future__ import annotations

import json
import re
import shutil
import zipfile
from pathlib import Path

COMPAT = Path("extensions/plugins/compatibility/compatibility.py")
COMPAT_RE = re.compile(r"msvc_fallback\s*=\s*\{[^}]*\}\.get\(compiler_version\)")
COMPAT_HEADER_RE = re.compile(r"\A# This file was generated by Conan.*\n(#.*will destroy your changes\.\n)?")
DEFAULT_FALLBACKS = {"195": "194", "194": "193"}
CONFIG_PATH_IN_RAW = "config/team-config.zip"


class TeamConfigError(Exception):
    pass


def patched_compat(home: Path, fallbacks: dict) -> str | None:
    """Conan's own compatibility plugin with our MSVC fallbacks, or None if it can't be patched.

    The plugin is taken from `home`, i.e. it matches the Conan version that generated it.
    """
    path = home / COMPAT
    if not fallbacks or not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    if not COMPAT_RE.search(text):
        return None
    text = COMPAT_RE.sub(f"msvc_fallback = {json.dumps(fallbacks)}.get(compiler_version)", text)
    # Without this header change Conan would overwrite the file with its default.
    note = "# Customised for the team (MSVC fallbacks) by team_config.py - re-export after upgrading Conan.\n"
    return note + COMPAT_HEADER_RE.sub("", text, count=1)


def remotes_json(settings: dict) -> str:
    return json.dumps({"remotes": [{"name": settings["nexus_remote"], "url": settings["nexus_url"],
                                    "verify_ssl": True}]}, indent=1) + "\n"


def global_conf(settings: dict, conan_version: str = "") -> str:
    lines = ["# Team Conan configuration - installed with `conan config install`. Do not edit here;",
             "# ask the Conan admin to change it and re-run the install command."]
    m = re.match(r"(\d+)\.(\d+)", conan_version)
    if m:
        # the compatibility plugin below was generated by this Conan version
        lines.append(f"core:required_conan_version = >={m.group(1)}.{m.group(2)}")
    if settings.get("raw_url"):
        # list value = Python literal; only Nexus, never the internet
        lines.append(f"core.sources:download_urls = {json.dumps([settings['raw_url']])}")
    return "\n".join(lines) + "\n"


def readme(settings: dict, profiles: list[str], build_profile: str, url: str) -> str:
    install = f"-pr:h <profile> -pr:b {build_profile}" if build_profile else "-pr:a <profile>"
    source = url or "team-config.zip"
    return f"""Team Conan configuration
========================

Requires Conan 2 on your PATH (the portable build or a pip install). Install or update the configuration with:

    conan config install {source}
    conan remote login {settings['nexus_remote']} <your Nexus username>

What it does to your Conan home (run `conan config home` to see where that is):
  - remotes.json  REPLACED: the only remote is '{settings['nexus_remote']}' ({settings['nexus_url']})
  - global.conf   REPLACED: --build=missing downloads upstream sources from Nexus, not the internet
  - compatibility plugin REPLACED: newer MSVC may use binaries built with the previous version
  - profiles added or overwritten: {', '.join(profiles) or '(none)'}

If you have your own global.conf or remotes, back them up first: they are overwritten.
To undo, restore your backup (or delete those files and Conan recreates its defaults).

Then use Conan as normal, e.g.:

    conan install . {install} --build=missing
{f'''
Always pass  -pr:b {build_profile}  as shown: packages in Nexus were built with that
build profile, and a different one can make Conan rebuild tools from source.
''' if build_profile else ''}
If a package is missing from Nexus, ask the Conan admin to mirror it
(name/version + which profile you are using).

Moving from the old team_setup.py? Run  python team_setup.py revert  with your old copy
first, then the install command above.
"""


def build(dest: Path, settings: dict, profiles: list[str], home: Path, conan_version: str = "",
          url: str = "", log=print) -> Path:
    """Write the team configuration folder to `dest` (emptied first). Returns dest."""
    if not settings.get("nexus_url"):
        raise TeamConfigError("The Nexus Conan repo URL is not set - fill it in under Settings.")
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "profiles").mkdir(parents=True)
    (dest / "remotes.json").write_text(remotes_json(settings), encoding="utf-8")
    (dest / "global.conf").write_text(global_conf(settings, conan_version), encoding="utf-8")
    for name in profiles:
        src = home / "profiles" / name
        if not src.is_file():
            raise TeamConfigError(f"Profile '{name}' not found in {home / 'profiles'}")
        target = dest / "profiles" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
    fallbacks = settings.get("msvc_fallbacks", DEFAULT_FALLBACKS)
    compat = patched_compat(home, fallbacks)
    if compat is not None:
        (dest / COMPAT).parent.mkdir(parents=True)
        (dest / COMPAT).write_text(compat, encoding="utf-8")
    elif fallbacks:
        log("WARNING: could not add the MSVC fallbacks - Conan's compatibility plugin was not "
            "found or has an unexpected layout. The team config ships without it.")
    (dest / "README.txt").write_text(
        readme(settings, profiles, settings.get("build_profile", ""), url), encoding="utf-8")
    (dest / ".conanignore").write_text("README.txt\n", encoding="utf-8")
    return dest


def make_zip(src: Path, zip_path: Path) -> None:
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(p for p in src.rglob("*") if p.is_file()):
            z.write(f, f.relative_to(src).as_posix())
